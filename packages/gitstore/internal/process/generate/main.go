//go:build ignore

// Generate private, reproducible Linux helper images from this module's source.
package main

import (
	"bytes"
	"compress/gzip"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
)

func main() {
	root, err := filepath.Abs("../../../..")
	must(err)
	temporary, err := os.MkdirTemp("", "fireweed-reaper-build-")
	must(err)
	defer os.RemoveAll(temporary)
	arches := []string{"386", "amd64", "arm", "arm64", "loong64", "mips", "mipsle", "mips64", "mips64le", "ppc64", "ppc64le", "riscv64", "s390x"}
	if len(os.Args) > 1 {
		arches = os.Args[1:]
	}
	for _, arch := range arches {
		output := filepath.Join(temporary, "reaper-"+arch)
		command := exec.Command("go", "build", "-trimpath", "-buildvcs=false", "-ldflags=-s -w -buildid=", "-o", output, "./packages/gitstore/internal/supervisor")
		command.Dir = root
		command.Env = append(os.Environ(), "CGO_ENABLED=0", "GOOS=linux", "GOARCH="+arch, "GOAMD64=v1", "GOARM=5", "GOMIPS=softfloat", "GOMIPS64=softfloat")
		command.Stdout, command.Stderr = os.Stdout, os.Stderr
		must(command.Run())
		binary, err := os.ReadFile(output)
		must(err)
		var compressed bytes.Buffer
		writer, err := gzip.NewWriterLevel(&compressed, gzip.BestCompression)
		must(err)
		_, err = writer.Write(binary)
		must(err)
		must(writer.Close())
		must(os.WriteFile("reaper_linux_"+arch+".gz", compressed.Bytes(), 0644))
		source := fmt.Sprintf("// Code generated by go generate; DO NOT EDIT.\npackage process\n\nimport _ \"embed\"\n\n//go:embed reaper_linux_%s.gz\nvar compressedReaper []byte\n", arch)
		must(os.WriteFile("image_linux_"+arch+".go", []byte(source), 0644))
		fmt.Printf("generated linux/%s: %d bytes\n", arch, compressed.Len())
	}
}
func must(err error) {
	if err != nil {
		panic(err)
	}
}
