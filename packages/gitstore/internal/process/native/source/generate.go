//go:build ignore

// Run from the native directory. Native objects are part of the disposable
// implementation, allowing go build/go install with CGO_ENABLED=0 and no
// runtime compiler or helper installation.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"sort"
	"strings"
)

func main() {
	for _, arch := range []string{"arm64", "amd64"} {
		clangArch := arch
		if arch == "amd64" {
			clangArch = "x86_64"
		}
		output := "anchor_darwin_" + arch + ".syso"
		cmd := exec.Command("cc", "-O2", "-fno-common", "-fno-stack-protector", "-arch", clangArch, "-c", "source/anchor.c", "-o", output)
		if out, err := cmd.CombinedOutput(); err != nil {
			panic(fmt.Sprintf("compile %s: %v: %s", arch, err, out))
		}
		out, err := exec.Command("nm", "-u", output).Output()
		if err != nil {
			panic(err)
		}
		names := []string{}
		for _, line := range strings.Split(string(out), "\n") {
			name := strings.TrimSpace(line)
			if strings.HasPrefix(name, "_") {
				names = append(names, strings.TrimPrefix(name, "_"))
			}
		}
		sort.Strings(names)
		var text bytes.Buffer
		fmt.Fprintln(&text, "// Code generated by go generate; DO NOT EDIT.\n\npackage native\n\nimport _ \"unsafe\"\n")
		for _, name := range names {
			fmt.Fprintf(&text, "//go:cgo_import_dynamic %s %s \"/usr/lib/libSystem.B.dylib\"\n", name, name)
		}
		source, err := format.Source(text.Bytes())
		if err != nil {
			panic(err)
		}
		if err = os.WriteFile("imports_darwin_"+arch+".go", source, 0644); err != nil {
			panic(err)
		}
	}
}
