#!/usr/bin/env python3
"""Render a binary Homebrew formula from GoReleaser's local artifacts."""

import hashlib
import json
import re
import sys
from pathlib import Path


def render(dist):
    version = json.loads((dist / "metadata.json").read_text())["version"]
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?", version):
        raise ValueError(f"unsupported release version: {version!r}")
    checksums = {}
    for line in (dist / "fireweed_checksums.txt").read_text().splitlines():
        digest, name = line.split()
        if not re.fullmatch(r"[0-9a-f]{64}", digest) or name in checksums:
            raise ValueError(f"invalid or duplicate checksum: {name}")
        checksums[name] = digest

    lines = [
        "# Generated by fireweed/scripts/homebrew.py; do not edit.",
        "class Fireweed < Formula",
        '  desc "Local CLI for checked spec-driven development"',
        '  homepage "https://github.com/lurkshark/fireweed"',
        f'  version "{version}"',
        '  license "GPL-3.0-only"',
        "",
    ]
    for os_name, brew_os in (("darwin", "macos"), ("linux", "linux")):
        lines.append(f"  on_{brew_os} do")
        for arch, brew_arch in (("arm64", "arm"), ("amd64", "intel")):
            name = f"fireweed_{version}_{os_name}_{arch}.tar.gz"
            digest = checksums[name]
            actual = hashlib.sha256((dist / name).read_bytes()).hexdigest()
            if digest != actual:
                raise ValueError(f"checksum mismatch: {name}")
            lines.extend([
                f"    on_{brew_arch} do",
                f'      url "https://github.com/lurkshark/fireweed/releases/download/v{version}/{name}"',
                f'      sha256 "{digest}"',
                "    end",
            ])
        lines.extend(["  end", ""])
    lines.extend([
        '  depends_on "git"',
        "",
        "  def install",
        '    bin.install "fireweed"',
        "  end",
        "",
        "  test do",
        '    assert_equal version.to_s, shell_output("#{bin}/fireweed version").strip',
        "  end",
        "end",
    ])
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: python3 scripts/homebrew.py <goreleaser-dist-directory>")
    try:
        print(render(Path(sys.argv[1])), end="")
    except (OSError, ValueError, KeyError) as error:
        sys.exit(f"homebrew: {error}")
